// Tiny JSON field reader for the flat config object.
std::string cfg_str(const std::string &obj, const char *key) {
    std::string k = std::string("\"") + key + "\"";
    std::size_t p = obj.find(k);
    if (p == std::string::npos) return "";
    p = obj.find(':', p + k.size());
    if (p == std::string::npos) return "";
    ++p;
    while (p < obj.size() && (obj[p] == ' ' || obj[p] == '\t')) ++p;
    if (p >= obj.size()) return "";
    if (obj[p] == '"') {
        std::size_t e = obj.find('"', p + 1);
        return e == std::string::npos ? "" : obj.substr(p + 1, e - p - 1);
    }
    std::size_t e = p;
    while (e < obj.size() && (std::isalnum(static_cast<unsigned char>(obj[e])) || obj[e] == '.')) ++e;
    return obj.substr(p, e - p);
}

const char *status_name(uint8_t st) {
    switch (st) {
    case MKTSIM_ST_SYMBOL_NOT_FOUND: return "symbol_not_found";
    case MKTSIM_ST_ORDER_NOT_FOUND: return "order_not_found";
    case MKTSIM_ST_NOT_ENOUGH_LIQUIDITY: return "no_liquidity";
    case MKTSIM_ST_FOK_FAILED: return "fok_unfillable";
    case MKTSIM_ST_INVALID_PRICE: return "invalid_price";
    case MKTSIM_ST_INVALID_QTY: return "invalid_qty";
    case MKTSIM_ST_DUPLICATE: return "duplicate";
    case MKTSIM_ST_OK: return "no_liquidity"; // nothing done
    default: return "failed";
    }
}

struct Conn {
    int fd;
    mktsim_session *session;
    std::string rx, tx;
    std::uint64_t next_req = 1;
    std::unordered_map<std::uint64_t, std::string> pending;  // request_id -> client id
    std::unordered_map<std::uint64_t, std::string> by_order; // order_id -> client id
    std::unordered_map<std::string, std::uint64_t> by_client; // client id -> order_id (0 = pending)
};

struct Adapter {
    const mktsim_exchange_api *api;
    mktsim_exchange *ex;
    std::uint16_t port = {{PORT}};
    std::string bind = "0.0.0.0";
    int listen_fd = -1;
    std::thread thread;
    std::atomic<bool> running{false};
    std::vector<Conn *> conns;

    void log(const std::string &m) { api->log(ex, kAdapterName, m.c_str()); }

    void emit(Conn &c, protocol::Outbound ev) { c.tx += protocol::encode(ev); }

    void reject(Conn &c, const std::string &id, const char *why) {
        protocol::Outbound ev(protocol::Outbound::Rejected, id);
        ev.reason = why;
        emit(c, ev);
    }

    void handle_frame(Conn &c, std::string_view frame) {
        auto m = protocol::decode(frame);
        if (!m) {
            protocol::Outbound ev(protocol::Outbound::Error);
            ev.reason = "expected NEW, MARKET, CANCEL, MODIFY or PING";
            emit(c, ev);
            return;
        }
        switch (m->kind) {
        case protocol::Inbound::Ping:
            emit(c, protocol::Outbound(protocol::Outbound::Pong));
            return;

        case protocol::Inbound::New: {
            if (m->client_id.empty() || m->symbol.empty())
                return reject(c, m->client_id, "bad_request");
            if (c.by_client.count(m->client_id))
                return reject(c, m->client_id, "duplicate");
            uint32_t symbol_id;
            if (api->resolve_symbol(ex, m->symbol.data(), m->symbol.size(), &symbol_id) != MKTSIM_OK)
                return reject(c, m->client_id, "symbol_not_found");
            mktsim_order_req r{};
            r.request_id = c.next_req++;
            r.kind = MKTSIM_REQ_NEW;
            r.side = m->side == 'S' ? MKTSIM_SELL : MKTSIM_BUY;
            r.ord_type = m->market ? MKTSIM_MARKET : MKTSIM_LIMIT;
            r.tif = m->tif == 'I' ? MKTSIM_IOC : m->tif == 'F' ? MKTSIM_FOK : MKTSIM_GTC;
            if (r.ord_type == MKTSIM_MARKET && r.tif == MKTSIM_GTC)
                r.tif = MKTSIM_IOC;
            r.symbol_id = symbol_id;
            r.qty = m->qty;
            r.price = m->price;
            int rc = api->submit(c.session, &r);
            if (rc != MKTSIM_OK)
                return reject(c, m->client_id, rc == MKTSIM_EBUSY ? "busy" : "bad_request");
            c.pending[r.request_id] = m->client_id;
            c.by_client[m->client_id] = 0;
            return;
        }

        case protocol::Inbound::Cancel:
        case protocol::Inbound::Modify: {
            auto it = c.by_client.find(m->client_id);
            if (it == c.by_client.end() || it->second == 0)
                return reject(c, m->client_id, "order_not_found");
            mktsim_order_req r{};
            r.request_id = c.next_req++;
            r.kind = m->kind == protocol::Inbound::Cancel ? MKTSIM_REQ_CANCEL : MKTSIM_REQ_MODIFY;
            r.order_id = it->second;
            if (m->kind == protocol::Inbound::Modify) {
                r.qty = m->qty;
                r.price = m->price;
            }
            int rc = api->submit(c.session, &r);
            if (rc != MKTSIM_OK)
                return reject(c, m->client_id, "busy");
            c.pending[r.request_id] = m->client_id;
            return;
        }
        }
    }

    static void on_report(void *user, const mktsim_report *r) {
        auto &c = *static_cast<Conn *>(user);
        std::string id;
        if (r->request_id) {
            auto p = c.pending.find(r->request_id);
            if (p != c.pending.end()) {
                id = p->second;
                if (r->kind != MKTSIM_RPT_EXECUTION)
                    c.pending.erase(p);
            }
        }
        if (id.empty()) {
            auto b = c.by_order.find(r->order_id);
            if (b != c.by_order.end())
                id = b->second;
        }
        if (id.empty())
            return; // not this connection's order

        protocol::Outbound ev(protocol::Outbound::Error, id);
        ev.order_id = r->order_id;
        switch (r->kind) {
        case MKTSIM_RPT_ACCEPTED:
            c.by_order[r->order_id] = id;
            c.by_client[id] = r->order_id;
            ev.kind = protocol::Outbound::Accepted;
            ev.qty = r->qty; ev.price = r->price; ev.leaves = r->leaves_qty;
            break;
        case MKTSIM_RPT_REJECTED:
            c.by_client.erase(id);
            ev.kind = protocol::Outbound::Rejected;
            ev.reason = status_name(r->status);
            break;
        case MKTSIM_RPT_CANCELLED:
            c.by_client.erase(id);
            c.by_order.erase(r->order_id);
            ev.kind = protocol::Outbound::Cancelled;
            break;
        case MKTSIM_RPT_MODIFIED:
            ev.kind = protocol::Outbound::Modified;
            ev.qty = r->qty; ev.price = r->price; ev.leaves = r->leaves_qty;
            break;
        case MKTSIM_RPT_EXECUTION:
            ev.kind = protocol::Outbound::Exec;
            ev.qty = r->last_qty; ev.price = r->price; ev.match_id = r->match_id;
            ev.leaves = r->leaves_qty;
            if (r->leaves_qty == 0) { // order is done; release the client id
                c.by_client.erase(id);
                c.by_order.erase(r->order_id);
            }
            break;
        default:
            return;
        }
        c.tx += protocol::encode(ev);
    }

    void run() {
        std::vector<pollfd> pfds;
        char buf[16384];
        while (running.load(std::memory_order_relaxed)) {
            pfds.clear();
            pfds.push_back({listen_fd, POLLIN, 0});
            for (auto *c : conns)
                pfds.push_back({c->fd, static_cast<short>(POLLIN | (c->tx.empty() ? 0 : POLLOUT)), 0});
            int n = ::poll(pfds.data(), pfds.size(), 1);
            if (n > 0 && (pfds[0].revents & POLLIN)) {
                for (;;) {
                    int fd = ::accept(listen_fd, nullptr, nullptr);
                    if (fd < 0)
                        break;
                    int one = 1;
                    ::setsockopt(fd, IPPROTO_TCP, TCP_NODELAY, &one, sizeof(one));
                    ::fcntl(fd, F_SETFL, ::fcntl(fd, F_GETFL, 0) | O_NONBLOCK);
                    auto *c = new Conn{};
                    c->fd = fd;
                    c->session = api->open_session(ex, kAdapterName);
                    conns.push_back(c);
                }
            }
            for (std::size_t i = 0; i < conns.size();) {
                Conn &c = *conns[i];
                bool dead = false;
                short rev = (i + 1 < pfds.size()) ? pfds[i + 1].revents : 0;
                if (rev & (POLLERR | POLLHUP | POLLNVAL))
                    dead = true;
                if (!dead && (rev & POLLIN)) {
                    ssize_t r = ::recv(c.fd, buf, sizeof(buf), 0);
                    if (r <= 0 && !(r < 0 && (errno == EAGAIN || errno == EWOULDBLOCK)))
                        dead = true;
                    else if (r > 0) {
                        c.rx.append(buf, r);
                        std::size_t len;
                        while ((len = protocol::frame_end(c.rx)) != 0) {
                            std::string frame = c.rx.substr(0, len);
                            c.rx.erase(0, len);
                            handle_frame(c, frame);
                        }
                        if (c.rx.size() > (1u << 20))
                            dead = true; // a megabyte without a frame boundary
                    }
                }
                if (!dead) {
                    api->poll(c.session, &Adapter::on_report, &c, 1024);
                    while (!c.tx.empty()) {
                        ssize_t w = ::send(c.fd, c.tx.data(), c.tx.size(), 0);
                        if (w < 0) {
                            if (errno != EAGAIN && errno != EWOULDBLOCK)
                                dead = true;
                            break;
                        }
                        c.tx.erase(0, w);
                    }
                }
                if (dead) {
                    api->close_session(c.session);
                    ::close(c.fd);
                    delete conns[i];
                    conns.erase(conns.begin() + i);
                    pfds.erase(pfds.begin() + i + 1);
                } else {
                    ++i;
                }
            }
        }
        for (auto *c : conns) {
            api->close_session(c->session);
            ::close(c->fd);
            delete c;
        }
        conns.clear();
    }
};

