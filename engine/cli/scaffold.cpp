std::string library_path(const Spec &spec) {
    return (spec.dir / "build" / spec.name).string();
}

std::string generate(const Spec &spec) {
    std::error_code ec;
    if (spec.name.empty())
        return "project name is empty";
    for (char c : spec.name)
        if (!(std::isalnum(static_cast<unsigned char>(c)) || c == '_'))
            return "project name must be letters, digits and _ only";
    if (fs::exists(spec.dir / "src" / "protocol.hpp", ec))
        return spec.dir.string() + " already contains a scaffolded adapter";

    fs::path api = spec.repo / "gateway" / "include" / "ingress" / "api.h";
    if (!fs::is_regular_file(api, ec))
        return "cannot find the ingress API header at " + api.string();

    auto sub = [&](const char *tpl) {
        return replace_all(replace_all(tpl, "{{NAME}}", spec.name), "{{PORT}}", std::to_string(spec.port));
    };

    std::string err;
    if (!write_file(spec.dir / "CMakeLists.txt", sub(kCMake), err)) return err;
    if (!write_file(spec.dir / "README.md", sub(kReadme), err)) return err;
    if (!write_file(spec.dir / "src" / "protocol.hpp", sub(kProtocol), err)) return err;
    if (!write_file(spec.dir / "src" / "adapter.cpp", sub(kAdapter), err)) return err;
    if (!write_file(spec.dir / ".gitignore", kGitignore, err)) return err;
    fs::create_directories(spec.dir / "include" / "ingress", ec);
    fs::copy_file(api, spec.dir / "include" / "ingress" / "api.h",
                  fs::copy_options::overwrite_existing, ec);
    if (ec)
        return "cannot copy api.h: " + ec.message();
    return "";
}

int build(const Spec &spec) {
    std::string dir = spec.dir.string();
    auto q = [](const std::string &s) { return "'" + s + "'"; };
    std::string cmd = "cmake -S " + q(dir) + " -B " + q(dir + "/build") +
                      " -DCMAKE_BUILD_TYPE=Release >/dev/null && cmake --build " +
                      q(dir + "/build") + " 2>&1 | grep -E 'error|warning|Built target' || true";
    int rc = std::system(cmd.c_str());
    (void)rc;
    // Success is the library existing
    std::error_code ec;
    std::string base = library_path(spec);
    return (fs::exists(base + ".dylib", ec) || fs::exists(base + ".so", ec)) ? 0 : 1;
}

